from unittest import TestCase, main


# === ЧАСТЬ 1: Рабочий код калькулятора ===
class Calculator:
    # Метод, который мы будем тестировать (принимает два числа и складывает их)
    def add(self, a, b):
        return a + b


# === ЧАСТЬ 2: Юнит-тест (то, что начала писать учитель) ===
# Тестовый класс ОБЯЗАТЕЛЬНО должен наследоваться от TestCase
class TestCalculator(TestCase):

    def test_add(self):
        # 1. Создаем объект нашего калькулятора
        calc = Calculator()

        # 2. Вызываем метод add с тестовыми числами 2 и 3
        result = calc.add(2, 3)

        # 3. Сравниваем результат. Мы ожидаем, что 2 + 3 должно быть равно 5
        # Метод assertEqual принимает два аргумента: (фактический_результат, ожидаемый_результат)
        self.assertEqual(result, 5)


# Этот блок нужен, чтобы запустить тесты прямо из файла
if __name__ == "__main__":
    main()